package jsmath

import "testing"

func TestToFixedComoJS(t *testing.T) {
	// Lo que da Node 22 para cada uno.
	for _, c := range []struct {
		v    float64
		d    int
		esJS string
	}{
		{0, 2, "0.00"}, {0.005, 2, "0.01"}, {0.015, 2, "0.01"}, {0.125, 2, "0.13"}, {1.005, 2, "1.00"},
		{1.255, 2, "1.25"}, {2.675, 2, "2.67"}, {10.235, 2, "10.23"}, {84500, 2, "84500.00"}, {84500.5, 2, "84500.50"},
		{1e21, 2, "1e+21"}, {123.456, 2, "123.46"}, {-1.005, 2, "-1.00"}, {0.1 + 0.2, 2, "0.30"}, {-0.125, 2, "-0.13"},
		{2.5, 0, "3"}, {-2.5, 0, "-3"}, {0.5, 0, "1"}, {1.45, 1, "1.4"}, {-0.001, 2, "-0.00"}, {12.345, 2, "12.35"},
	} {
		if g := ToFixed(c.v, c.d); g != c.esJS {
			t.Errorf("(%v).toFixed(%d) = %q, JS %q", c.v, c.d, g, c.esJS)
		}
	}
}
